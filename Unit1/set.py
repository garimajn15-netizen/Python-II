# 2.1 Create and access set elements
set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}

print("Set1:", set1)
print("Set2:", set2)

# 2.2 Union of sets
print("Union:", set1 | set2)

# 2.3 Intersection of sets
print("Intersection:", set1 & set2)

# 2.4 Difference of sets
print("Difference (Set1 - Set2):", set1 - set2)
